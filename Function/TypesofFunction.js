// Named Function

function addition(a,b,c)
{
    console.log(a+b+c);
}

addition(40,20,40);


// Function expression

let greet=function(){
    console.log("Hello");
};

greet();


// Arrow Function

const multiply=(a,b)=>{
    console.log(a*b);
}

multiply(10,20);

// Single-line arrow function

const add = (a, b) => a + b;

console.log(add(10, 20));


