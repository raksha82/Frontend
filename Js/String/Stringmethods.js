// String

// Length
let name="Raksha";
console.log(name.length); //6


// Uppercase
console.log(name.toUpperCase()); //RAKSHA

// Lowercase
console.log(name.toLowerCase()); //raksha

// CharAt
console.log(name.charAt(5)); //a

// At() Supports negative index
console.log(name.at(-6)); //R

// indexOf
console.log(name.indexOf("a")); //1


// Lastindexof
console.log(name.lastIndexOf("a")); //5

// includes
console.log(name.includes("ks")); //true